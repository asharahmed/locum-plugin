#!/usr/bin/env python3
"""Regenerate hooks/schemas.ts from a Claude Code build's plugin type file.

Plugins can read built-in tool names and descriptions but not their input
schemas, so the mod ships them. Rerun after a Claude Code update:

    python3 -I scripts/gen-schemas.py <path>/plugin-authoring/types/claude-code.d.ts

The type file is written when the plugin-authoring skill loads. Needs npx
(it runs ts-json-schema-generator on the BuiltinToolInputs interface).

Only the schemas' structure is taken from the type file. Every parameter
description is replaced with Locum's own wording from tool-descriptions.json;
a parameter without an entry there gets no description, and is listed so one
can be written. To reapply the descriptions to the committed schemas without
regenerating them:

    python3 -I scripts/gen-schemas.py --descriptions-only
"""
import json
import pathlib
import subprocess
import sys
import tempfile

# The built-in tools a background subagent keeps (docs: sub-agents, "Available
# tools"). Background is the Agent tool's default; SubagentHandback is added by
# the mod itself. A tool the session doesn't have is skipped at run time.
SUBAGENT_TOOLS = [
    "Read", "Grep", "Glob", "LSP", "Bash", "PowerShell", "Edit", "Write", "NotebookEdit",
    "WebFetch", "WebSearch", "TodoWrite", "Skill", "ToolSearch", "EnterWorktree",
    "ExitWorktree", "Monitor", "TaskStop", "SendMessage", "Artifact",
]
# Parameters OpenRouter subagents are not offered
EXCLUDE = {"Bash": {"dangerouslyDisableSandbox"}, "PowerShell": {"dangerouslyDisableSandbox"}}
GENERATOR = "ts-json-schema-generator@2.3.0"
HERE = pathlib.Path(__file__).resolve().parent
DEST = HERE.parent / "hooks" / "schemas.ts"
HEADER = (
    "// Generated by scripts/gen-schemas.py. The schemas' structure comes from Claude Code's\n"
    "// plugin type file; every description is Locum's own (scripts/tool-descriptions.json).\n"
    "// Input schemas of every built-in tool, and the ones a background subagent keeps.\n"
)


def own_descriptions(tools):
    """Replace each description with ours, keyed Tool.path; drop any without one."""
    ours = json.loads((HERE / "tool-descriptions.json").read_text())
    unmatched = []

    def walk(node, path, tool):
        if isinstance(node, list):
            for i, item in enumerate(node):
                walk(item, f"{path}[{i}]", tool)
            return
        if not isinstance(node, dict):
            return
        if isinstance(node.get("description"), str):
            key = f"{tool}{path}"
            if key in ours:
                node["description"] = ours[key]
            else:
                del node["description"]
                unmatched.append(key)
        for k, v in node.items():
            if k != "description":
                walk(v, f"{path}.{k}", tool)

    for name, tool in tools.items():
        walk(tool, "", name)
    return unmatched


def write(tools, subagent_tools):
    unmatched = own_descriptions(tools)
    DEST.write_text(
        HEADER
        + f"export const TOOL_SCHEMAS: Record<string, Record<string, unknown>> = {json.dumps(tools, indent=2)}\n\n"
        f"export const SUBAGENT_TOOLS: readonly string[] = {json.dumps(subagent_tools)}\n"
    )
    if unmatched:
        print(f"no description of ours for {len(unmatched)} parameter(s), left without one; add them to tool-descriptions.json:")
        for key in unmatched:
            print(f"  {key}")


def extract_interface(text):
    start = text.index("declare module 'claude-code' {\n  interface BuiltinToolInputs {")
    body_start = text.index("\n  interface BuiltinToolInputs {", start) + 1
    body_end = text.index("\n  }\n", body_start) + 4
    return "export " + text[body_start:body_end].strip() + "\n"


def main(src):
    text = pathlib.Path(src).read_text()
    with tempfile.TemporaryDirectory() as tmp:
        inputs = pathlib.Path(tmp) / "inputs.ts"
        out = pathlib.Path(tmp) / "schema.json"
        inputs.write_text(extract_interface(text))
        subprocess.run(
            ["npx", "-y", GENERATOR, "--path", str(inputs), "--type", "BuiltinToolInputs",
             "--no-type-check", "--expose", "none", "-o", str(out)],
            check=True, capture_output=True, text=True,
        )
        schema = json.loads(out.read_text())

    root = schema.get("definitions", {}).get("BuiltinToolInputs", schema)
    definitions = {k: v for k, v in schema.get("definitions", {}).items() if k != "BuiltinToolInputs"}
    tools = {}
    # Every built-in: the main session can use them all, a subagent only SUBAGENT_TOOLS
    for name in sorted(root.get("properties", {})):
        tool = root["properties"][name]
        tool = json.loads(json.dumps(tool))
        for prop in EXCLUDE.get(name, ()):
            tool.get("properties", {}).pop(prop, None)
            if prop in tool.get("required", []):
                tool["required"].remove(prop)
        if "$ref" in json.dumps(tool) and definitions:
            tool["definitions"] = definitions
        tools[name] = tool

    missing = [n for n in SUBAGENT_TOOLS if n not in tools]
    write(tools, [n for n in SUBAGENT_TOOLS if n in tools])
    print(f"wrote {DEST}: {', '.join(tools)}" + (f" (not in this build: {', '.join(missing)})" if missing else ""))


def descriptions_only():
    """Reapply our descriptions to the committed schemas, leaving their structure as it is."""
    text = DEST.read_text()
    start = text.index("= {", text.index("TOOL_SCHEMAS")) + 2
    end = text.index("\n}\n", start) + 2
    tools = json.loads(text[start:end])
    subagent = json.loads(text[text.index("= [", text.index("SUBAGENT_TOOLS: readonly")) + 2:].strip())
    write(tools, subagent)
    print(f"rewrote the descriptions in {DEST}")


if __name__ == "__main__":
    if sys.argv[1:] == ["--descriptions-only"]:
        descriptions_only()
    else:
        main(sys.argv[1])
